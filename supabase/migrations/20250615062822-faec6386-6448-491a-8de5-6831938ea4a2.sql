-- Define a type for player status, now including 'UNKNOWN'
CREATE TYPE public.player_status AS ENUM ('IN', 'OUT', 'MAYBE', 'UNKNOWN');

-- Create a table to link players to matches with their availability status
CREATE TABLE public.player_statuses (
  match_id integer NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
  player_id integer NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
  status public.player_status NOT NULL,
  PRIMARY KEY (match_id, player_id)
);

-- Enable Row Level Security for data protection
ALTER TABLE public.players ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.player_statuses ENABLE ROW LEVEL SECURITY;

-- Create policies to allow read access for all users
CREATE POLICY "Allow public read access to players" ON public.players FOR SELECT USING (true);
CREATE POLICY "Allow public read access to matches" ON public.matches FOR SELECT USING (true);

-- Create policies to allow all operations on player_statuses for all users
CREATE POLICY "Allow all access for all users" ON public.player_statuses FOR ALL USING (true) WITH CHECK (true);
